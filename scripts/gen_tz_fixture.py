#!/usr/bin/env python3
"""Generate test-host/fixtures/tz_fixture.h for the PosixTz / calendar host suites.

Oracle: IANA tzdata through Python's zoneinfo (on Windows the `tzdata` package).
The POSIX strings under test are the tzfile footers (RFC 8536 §3.3) of the same
data, so for 2024..2040 the footer rule and the zone history coincide; glibc
evaluates the same footers.

Contents:
  - 10 000 instants from a splitmix64 stream (the C++ test regenerates them from
    the seed), cycling over the first 4 zones; per instant the expected UTC
    offset in quarter hours.
  - every transition 2024..2040 of every zone (first second of the new offset).
  - local month starts 2026..2030 (PEP 495 fold=0: gap -> shifted forward,
    fold -> earlier), the `cal::monthBounds` contract.

    python scripts/gen_tz_fixture.py           # (re)write the header
    python scripts/gen_tz_fixture.py --check   # exit 1 when the header is stale
"""
import argparse
import datetime as dt
import importlib.resources
import pathlib
import sys
import zoneinfo

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "test-host" / "fixtures" / "tz_fixture.h"

# The first 4 take the random instants (SES-LIB-006 acceptance 4). The rest
# exercise negative DST (Dublin), quoted names and /24 times (Santiago),
# negative rule times (Nuuk) through the transition and month tables.
ZONES = ["Europe/Kyiv", "Europe/London", "America/New_York", "Australia/Sydney",
         "Europe/Dublin", "America/Santiago", "America/Nuuk"]
RANDOM_ZONES = 4
COUNT = 10000
SEED = 0x5E5006
UTC = dt.timezone.utc
LO = int(dt.datetime(2024, 1, 1, tzinfo=UTC).timestamp())
HI = int(dt.datetime(2041, 1, 1, tzinfo=UTC).timestamp())
MONTH_YEARS = range(2026, 2031)
M64 = (1 << 64) - 1


def splitmix64(state):
    state = (state + 0x9E3779B97F4A7C15) & M64
    z = state
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & M64
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & M64
    return state, z ^ (z >> 31)


def tzfile_bytes(name):
    try:
        return importlib.resources.files("tzdata.zoneinfo").joinpath(*name.split("/")).read_bytes()
    except (ModuleNotFoundError, FileNotFoundError):
        for base in zoneinfo.TZPATH:
            p = pathlib.Path(base, name)
            if p.is_file():
                return p.read_bytes()
    raise SystemExit(f"tzfile for {name} not found (pip install tzdata)")


def footer(name):
    data = tzfile_bytes(name)
    if data[:4] != b"TZif" or data[4:5] < b"2":
        raise SystemExit(f"{name}: not a TZif v2+ file")
    return data.rstrip(b"\n").rsplit(b"\n", 1)[1].decode("ascii")


def tzdata_version():
    try:
        import tzdata
        return tzdata.IANA_VERSION
    except ModuleNotFoundError:
        return "system"


def offset(z, t):
    return int(dt.datetime.fromtimestamp(t, tz=z).utcoffset().total_seconds())


def transitions(z):
    out = []
    t, prev = LO, offset(z, LO)
    while t < HI:
        n = min(t + 3600, HI)
        cur = offset(z, n)
        if cur != prev:
            a, b = t, n  # offset(a) == prev, offset(b) != prev
            while b - a > 1:
                m = (a + b) // 2
                if offset(z, m) == prev:
                    a = m
                else:
                    b = m
            out.append((b, prev, cur))
            prev = cur
        t = n
    return out


def generate():
    zs = [zoneinfo.ZoneInfo(n) for n in ZONES]
    lines = [
        "// Generated by scripts/gen_tz_fixture.py - do not edit.",
        f"// Oracle: IANA tzdata {tzdata_version()} (Python {sys.version_info[0]}.{sys.version_info[1]} zoneinfo).",
        "#pragma once",
        "#include <stdint.h>",
        "",
        "namespace tzfx {",
        "",
        "struct Zone { const char* name; const char* posix; };",
        "constexpr Zone kZones[] = {",
    ]
    for n in ZONES:
        lines.append(f'    {{"{n}", "{footer(n)}"}},')
    lines += [
        "};",
        f"constexpr int kZoneCount = {len(ZONES)};",
        f"constexpr int kRandomZones = {RANDOM_ZONES};  // instant i is in zone i % kRandomZones",
        "",
        "// splitmix64 stream: utc_i = kLo + (next() % kSpan)",
        f"constexpr uint64_t kSeed = 0x{SEED:X}ULL;",
        f"constexpr int64_t kLo = {LO}LL, kSpan = {HI - LO}LL;  // [2024-01-01, 2041-01-01) UTC",
        f"constexpr int kCount = {COUNT};",
        "// expected utcoffset / 900 of instant i",
        "constexpr int8_t kOffQ[kCount] = {",
    ]
    state, row = SEED, []
    for i in range(COUNT):
        state, r = splitmix64(state)
        t = LO + r % (HI - LO)
        off = offset(zs[i % RANDOM_ZONES], t)
        assert off % 900 == 0
        row.append(str(off // 900))
        if len(row) == 32:
            lines.append("    " + ",".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ",".join(row) + ",")
    lines += [
        "};",
        "",
        "// first second of the new offset; offsets in seconds (local - UTC)",
        "struct Transition { uint8_t zone; int64_t utc; int32_t before, after; };",
        "constexpr Transition kTransitions[] = {",
    ]
    count_tr = 0
    for zi, z in enumerate(zs):
        for t, a, b in transitions(z):
            lines.append(f"    {{{zi}, {t}LL, {a}, {b}}},")
            count_tr += 1
    lines += [
        "};",
        f"constexpr int kTransitionCount = {count_tr};",
        "",
        "// UTC of local Y-M-01 00:00 (gap -> forward, fold -> earlier)",
        "struct MonthStart { uint8_t zone; int16_t y; uint8_t m; int64_t utc; };",
        "constexpr MonthStart kMonthStarts[] = {",
    ]
    count_ms = 0
    for zi, z in enumerate(zs):
        for y in MONTH_YEARS:
            for m in range(1, 13):
                t = int(dt.datetime(y, m, 1, tzinfo=z).timestamp())
                lines.append(f"    {{{zi}, {y}, {m}, {t}LL}},")
                count_ms += 1
    lines += [
        "};",
        f"constexpr int kMonthStartCount = {count_ms};",
        "",
        "}  // namespace tzfx",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if the header differs")
    args = ap.parse_args()
    text = generate()
    if args.check:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if cur != text:
            print(f"{OUT.relative_to(ROOT)} is stale - run scripts/gen_tz_fixture.py")
            return 1
        print("tz fixture up to date")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
